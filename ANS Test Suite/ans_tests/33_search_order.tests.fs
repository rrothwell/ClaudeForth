\ ============================================================
\ ANS test suite - Search-Order word set (Phase 1)
\ WORDLIST FORTH-WORDLIST GET-ORDER SET-ORDER FIND
\ SEARCH-WORDLIST GET-CURRENT SET-CURRENT DEFINITIONS
\ ONLY ALSO PREVIOUS FORTH ROOT VOCABULARY
\ Requires ttester.fs then 00_test_prelude.fs to be loaded first.
\ Written for this project (forth6809_stage_6g and later; the
\ first part also runs on 6f).
\ MARKER restores the search order too, so the system is left as
\ it was found, including the wordlists created here.
\ ============================================================
MARKER M33
TEST-BEGIN
DECIMAL

\ ---- initial state
T{ GET-ORDER -> FORTH-WORDLIST 1 }T
T{ GET-CURRENT -> FORTH-WORDLIST }T

\ ---- WORDLIST gives distinct wids
WORDLIST CONSTANT WL1
WORDLIST CONSTANT WL2
T{ WL1 WL2 = -> 0 }T
T{ WL1 FORTH-WORDLIST = -> 0 }T
T{ WORDLIST WL1 = -> 0 }T

\ ---- SEARCH-WORDLIST
T{ S" DUP" FORTH-WORDLIST SEARCH-WORDLIST SWAP ' DUP = -> -1 -1 }T
T{ S" IF" FORTH-WORDLIST SEARCH-WORDLIST NIP -> 1 }T
T{ S" NOSUCHWORD" FORTH-WORDLIST SEARCH-WORDLIST -> 0 }T
T{ S" DUP" WL1 SEARCH-WORDLIST -> 0 }T
T{ S" GET-ORDER" FORTH-WORDLIST SEARCH-WORDLIST NIP -> -1 }T

\ ---- SET-CURRENT: new words go into the current wordlist
T{ WL1 SET-CURRENT : TW1 123 ; GET-CURRENT -> WL1 }T
T{ FORTH-WORDLIST SET-CURRENT : TW2 234 ; GET-CURRENT -> FORTH-WORDLIST }T
T{ S" TW1" WL1 SEARCH-WORDLIST NIP -> -1 }T
T{ S" TW1" FORTH-WORDLIST SEARCH-WORDLIST -> 0 }T
T{ S" TW2" FORTH-WORDLIST SEARCH-WORDLIST NIP -> -1 }T
T{ S" TW2" WL1 SEARCH-WORDLIST -> 0 }T
T{ TW2 -> 234 }T
T{ WL2 SET-CURRENT : TW3 1 ; IMMEDIATE FORTH-WORDLIST SET-CURRENT -> }T
T{ S" TW3" WL2 SEARCH-WORDLIST NIP -> 1 }T

\ ---- SET-ORDER / GET-ORDER
T{ FORTH-WORDLIST WL1 2 SET-ORDER GET-ORDER -> FORTH-WORDLIST WL1 2 }T
T{ TW1 -> 123 }T
: TC1 TW1 ;
T{ FORTH-WORDLIST 1 SET-ORDER GET-ORDER -> FORTH-WORDLIST 1 }T
\ TW1 is no longer visible, but TC1 compiled earlier still runs
T{ TC1 -> 123 }T
T{ -1 SET-ORDER GET-ORDER -> FORTH-WORDLIST 1 }T

\ ---- the first wordlist in the order is searched first
T{ WL1 SET-CURRENT : TX 1 ; WL2 SET-CURRENT : TX 2 ; -> }T
T{ FORTH-WORDLIST SET-CURRENT -> }T
T{ FORTH-WORDLIST WL1 WL2 3 SET-ORDER TX -> 2 }T
T{ FORTH-WORDLIST WL2 WL1 3 SET-ORDER TX -> 1 }T
T{ FORTH-WORDLIST WL1 WL1 3 SET-ORDER TX -> 1 }T
T{ -1 SET-ORDER -> }T

\ ---- DEFINITIONS
T{ FORTH-WORDLIST WL1 2 SET-ORDER DEFINITIONS GET-CURRENT -> WL1 }T
T{ WL1 FORTH-WORDLIST 2 SET-ORDER DEFINITIONS GET-CURRENT -> FORTH-WORDLIST }T
T{ -1 SET-ORDER DEFINITIONS GET-CURRENT -> FORTH-WORDLIST }T

\ ---- the empty order leaves nothing but ROOT: restore through
\ ---- words compiled earlier
: TZ GET-ORDER 0 SET-ORDER GET-ORDER >R SET-ORDER R> ;
T{ TZ -> 0 }T
T{ GET-ORDER -> FORTH-WORDLIST 1 }T

\ ---- maximum order (8) accepts duplicates
: TD8 FORTH-WORDLIST 7 0 DO DUP LOOP 8 SET-ORDER
   GET-ORDER 8 0 DO NIP LOOP ;
T{ TD8 -> 8 }T
T{ -1 SET-ORDER -> }T

\ ---- errors
: TE1 FORTH-WORDLIST 9 SET-ORDER ;
: TE2 -2 SET-ORDER ;
: TE3 1234 SET-CURRENT ;
: TE4 1234 1 SET-ORDER ;
: TE5 1 SET-CURRENT ;
T{ ' TE1 CATCH -> -49 }T
T{ ' TE2 CATCH -> -50 }T
T{ ' TE3 CATCH -> -11 }T
T{ ' TE4 CATCH -> -11 }T
T{ ' TE5 CATCH -> -11 }T
T{ GET-ORDER -> FORTH-WORDLIST 1 }T

\ ---- ENVIRONMENT?
T{ S" WORDLISTS" ENVIRONMENT? -> 8 TRUE }T

\ ---- MARKER restores wordlists, search order and CURRENT
FORTH-WORDLIST WL1 2 SET-ORDER
MARKER MK1
WL1 SET-CURRENT : TM1 1 ; FORTH-WORDLIST SET-CURRENT : TM2 2 ;
WORDLIST CONSTANT WLX
WLX SET-CURRENT : TM3 3 ; FORTH-WORDLIST SET-CURRENT
WLX FORTH-WORDLIST 2 SET-ORDER
MK1
T{ GET-ORDER -> FORTH-WORDLIST WL1 2 }T
T{ GET-CURRENT -> FORTH-WORDLIST }T
T{ S" TM1" WL1 SEARCH-WORDLIST -> 0 }T
T{ S" TM2" FORTH-WORDLIST SEARCH-WORDLIST -> 0 }T
T{ S" MK1" FORTH-WORDLIST SEARCH-WORDLIST -> 0 }T
T{ S" TW1" WL1 SEARCH-WORDLIST NIP -> -1 }T
T{ -1 SET-ORDER -> }T

\ ---- Phase 2: ONLY ALSO PREVIOUS FORTH ROOT VOCABULARY
T{ ONLY GET-ORDER -> FORTH-WORDLIST 1 }T
T{ ALSO GET-ORDER -> FORTH-WORDLIST FORTH-WORDLIST 2 }T
T{ PREVIOUS GET-ORDER -> FORTH-WORDLIST 1 }T
T{ FORTH-WORDLIST WL1 2 SET-ORDER FORTH GET-ORDER -> FORTH-WORDLIST FORTH-WORDLIST 2 }T
T{ ONLY -> }T
: TDEPTH GET-ORDER DUP >R 0 DO DROP LOOP R> ;
VOCABULARY VOC1
VOCABULARY VOC2
T{ ALSO VOC1 DEFINITIONS : VW1 11 ; VW1 -> 11 }T
T{ GET-ORDER DROP GET-CURRENT = -> FORTH-WORDLIST TRUE }T
T{ ONLY FORTH DEFINITIONS -> }T
T{ S" VW1" FORTH-WORDLIST SEARCH-WORDLIST -> 0 }T
T{ ALSO VOC1 VW1 -> 11 }T
T{ PREVIOUS TDEPTH -> 1 }T
T{ ONLY FORTH ALSO VOC2 ALSO VOC1 TDEPTH -> 3 }T
T{ VOC2 TDEPTH -> 3 }T
T{ ONLY -> }T
ALSO VOC1 GET-ORDER DROP CONSTANT V1WID DROP PREVIOUS
T{ GET-ORDER -> FORTH-WORDLIST 1 }T
T{ ALSO VOC1 ALSO GET-ORDER -> FORTH-WORDLIST V1WID V1WID 3 }T
T{ PREVIOUS GET-ORDER -> FORTH-WORDLIST V1WID 2 }T
T{ PREVIOUS GET-ORDER -> FORTH-WORDLIST 1 }T
T{ ONLY -> }T
ALSO ROOT GET-ORDER DROP CONSTANT ROOTWID DROP PREVIOUS
T{ S" ONLY" ROOTWID SEARCH-WORDLIST NIP -> -1 }T
T{ S" DUP" ROOTWID SEARCH-WORDLIST -> 0 }T
T{ ROOTWID FORTH-WORDLIST = -> 0 }T
T{ ROOTWID WL1 = -> 0 }T
: TF2 ONLY 7 0 DO ALSO LOOP ALSO ;
T{ ' TF2 CATCH -> -49 }T
T{ ONLY TDEPTH -> 1 }T

HEX
TEST-END
